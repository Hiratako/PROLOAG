def _diagram(title: str, description: str, steps: tuple[tuple[str, str, str], ...]) -> str:
    """Small code-native diagram; escaped static copy, no external assets."""
    cards = []
    for index, (heading, first, second) in enumerate(steps):
        x = 28 + index * 273
        accent = index == 0
        fill, foreground, muted = ("#162942", "#ffffff", "#dce7f4") if accent else ("#ffffff", "#162942", "#526783")
        cards.append(f'''<rect x="{x}" y="72" width="245" height="151" rx="14" fill="{fill}" stroke="#cad7e6"/>
<text x="{x + 18}" y="104" font-size="14" fill="{muted}">0{index + 1}</text>
<text x="{x + 18}" y="139" font-size="23" font-weight="700" fill="{foreground}">{escape(heading)}</text>
<text x="{x + 18}" y="176" font-size="17" fill="{muted}">{escape(first)}</text>
<text x="{x + 18}" y="203" font-size="17" fill="{muted}">{escape(second)}</text>''')
        if index < len(steps) - 1:
            cards.append(f'<path d="M{x + 251} 148 h16 m-7 -6 7 6 -7 6" fill="none" stroke="#617c99" stroke-width="2"/>')
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="1120" height="256" viewBox="0 0 1120 256" role="img">
<title>{escape(title)}</title><desc>{escape(description)}</desc>
<rect width="1120" height="256" rx="20" fill="#f2f5fa"/>
<g font-family="Segoe UI,Yu Gothic,Meiryo,sans-serif"><text x="28" y="43" font-size="19" fill="#162942" font-weight="700">{escape(title)}</text>{''.join(cards)}</g></svg>'''


